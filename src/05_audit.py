"""Quality gate: the repository's automated referee.

Usage:  python src/05_audit.py [--full]

--full re-runs the analysis and figure scripts from the committed panel before checking.
Writes run_report.json (git-ignored) with pass/fail per check and exits non-zero on failure.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from core.io import PANEL, RESULTS, ROOT  # noqa: E402

REQUIRED = [
    "README.md", "TECHNICAL.md", "Makefile", "requirements.txt", ".gitignore", ".github/workflows/ci.yml",
    "data/raw/manifest.json", "data/processed/analytical_panel.parquet",
    "results/FINDINGS.md", "results/key_numbers.json", "results/original_benchmarks.csv",
    "results/sample_waterfall.csv", "results/summary_stats.csv", "results/regression_horserace.csv",
    "results/diagnostics_and_sensitivity.csv", "results/monte_carlo_validation.csv",
    "results/counterfactual_simulation.csv", "results/named_entities_table.csv",
    "results/fig1_primary_mechanism.png", "results/fig2_methodological_horserace.png",
    "results/fig3_structural_or_counterfactual.png", "results/fig4_heterogeneity_and_sensitivity.png",
    "src/01_data_pipeline.py", "src/02_econometric_suite.py", "src/03_structural_and_montecarlo.py",
    "src/04_visualization.py", "src/05_audit.py",
]
BANNED = ["crucially", "notably", "importantly", "it is worth noting", "delve", "landscape", "underscore",
          "stark", "nuanced", "tapestry", "testament", "shed light", "at the end of the day", "in today's"]
AUTHORSHIP = re.compile(r"\b(artificial intelligence|language model|LLM|ChatGPT|Claude|GPT-?\d|AI assistant|"
                        r"generated by|written by an? (AI|model)|as an AI)\b", re.I)
SECRET = re.compile(r"(gh[pousr]_[A-Za-z0-9]{20,}|sk-[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16}|"
                    r"(api[_-]?key|token|secret)\s*[:=]\s*['\"][A-Za-z0-9_\-]{16,}['\"])", re.I)
NUM = re.compile(r"(?<![\w.\-/])[-−]?\d{1,3}(?:,\d{3})+(?:\.\d+)?(?![\w])|(?<![\w.\-/])[-−]?\d+(?:\.\d+)?(?![\w/])")


def strip_markup(text: str, keep_math: bool = False) -> str:
    """Remove code, links, images, HTML comments, and (optionally) math from markdown."""
    text = re.sub(r"```.*?```", " ", text, flags=re.S)
    text = re.sub(r"`[^`]*`", " ", text)
    text = re.sub(r"<!--.*?-->", " ", text, flags=re.S)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", " ", text)
    text = re.sub(r"\]\([^)]*\)", "]", text)
    text = re.sub(r"https?://\S+", " ", text)
    if not keep_math:
        text = re.sub(r"\$\$.*?\$\$", " ", text, flags=re.S)
        text = re.sub(r"\$[^$\n]+\$", " ", text)
    return text


def prose_only(text: str) -> str:
    """Prose for word counts: no code, math, tables, headings, or reference lists."""
    t = strip_markup(text)
    t = cut_references(t)
    lines = [ln for ln in t.splitlines() if not ln.lstrip().startswith(("|", "#", ">"))]
    return "\n".join(lines)


def cut_references(text: str) -> str:
    m = re.search(r"^#+\s*(?:\d+\.\s*)?(References|Bibliography|Further reading.*)$", text, flags=re.M | re.I)
    return text[: m.start()] if m else text


def words(text: str) -> int:
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'\-.%]*", text))


def collect_values() -> np.ndarray:
    vals: list[float] = []

    def walk(o):
        if isinstance(o, bool):
            return
        if isinstance(o, (int, float)) and np.isfinite(o):
            vals.append(float(o))
        elif isinstance(o, dict):
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
        elif isinstance(o, str):
            for tok in re.findall(r"-?\d+(?:\.\d+)?", o):
                vals.append(float(tok))

    walk(json.loads((RESULTS / "key_numbers.json").read_text()))
    for f in RESULTS.glob("*.csv"):
        df = pd.read_csv(f)
        for c in df.columns:
            col = pd.to_numeric(df[c], errors="coerce").dropna()
            vals.extend(col.astype(float).tolist())
            if df[c].dtype == object:
                for s in df[c].dropna().astype(str):
                    vals.extend(float(t) for t in re.findall(r"-?\d+(?:\.\d+)?", s))
    panel = pd.read_parquet(PANEL)
    for c in panel.select_dtypes("number").columns:
        vals.extend(panel[c].dropna().astype(float).tolist())
    v = np.abs(np.array(vals))
    return np.unique(np.concatenate([v, 100 * v, v / 100]))


def untraced_numbers(path: Path, values: np.ndarray) -> list[str]:
    text = cut_references(strip_markup(path.read_text(), keep_math=False))
    text = re.sub(r"\b\d{4}Q[1-4]\b", " ", text)                 # quarter labels
    text = re.sub(r"\b(?:p|pp)\.\s*\d+(?:[-–]\d+)?", " ", text)  # page references
    text = re.sub(r"\b(?:S|Stage|Table|Figure|fig|Proposition|Lemma|Step|eq\.?|equation)\s*\(?\d+[a-z]?\)?", " ", text, flags=re.I)
    bad = []
    for m in NUM.finditer(text):
        tok = m.group(0).replace("−", "-").replace(",", "")
        x = abs(float(tok))
        dec = len(tok.split(".")[1]) if "." in tok else 0
        if dec == 0 and (x <= 12 or 1900 <= x <= 2100):
            continue  # small counts and calendar years
        tol = 0.5 * 10 ** (-dec) + 1e-9
        if not np.any(np.abs(values - x) <= tol):
            bad.append(tok)
    return bad


def main(full: bool) -> int:
    report: dict = {"checks": {}}
    ok = report["checks"]
    py = sys.executable

    if full:
        for script in ["02_econometric_suite.py", "03_structural_and_montecarlo.py", "04_visualization.py"]:
            r = subprocess.run([py, str(ROOT / "src" / script)], capture_output=True, text=True)
            ok[f"runs:{script}"] = {"pass": r.returncode == 0, "detail": r.stderr[-400:]}
    else:
        newest_input = PANEL.stat().st_mtime
        pipeline_outputs = {"sample_waterfall.csv", "missingness.csv"}
        stale = [f.name for f in RESULTS.glob("*.csv")
                 if f.name not in pipeline_outputs and f.stat().st_mtime < newest_input]
        ok["results_newer_than_panel"] = {"pass": not stale, "detail": stale}

    missing = [f for f in REQUIRED if not (ROOT / f).exists()]
    ok["required_files"] = {"pass": not missing, "detail": missing}

    r = subprocess.run([py, "-m", "pytest", "-q", str(ROOT / "tests")], capture_output=True, text=True, cwd=ROOT)
    ok["pytest"] = {"pass": r.returncode == 0, "detail": r.stdout.strip().splitlines()[-1] if r.stdout else r.stderr[-300:]}

    values = collect_values()
    for doc in ["README.md", "TECHNICAL.md", "results/FINDINGS.md"]:
        p = ROOT / doc
        if p.exists():
            bad = untraced_numbers(p, values)
            ok[f"numbers_traced:{doc}"] = {"pass": not bad, "detail": sorted(set(bad))[:40]}

    if (ROOT / "README.md").exists():
        n = words(prose_only((ROOT / "README.md").read_text()))
        ok["readme_words"] = {"pass": 2500 <= n <= 4500, "detail": n}
    if (ROOT / "TECHNICAL.md").exists():
        n = words(prose_only((ROOT / "TECHNICAL.md").read_text()))
        ok["technical_prose_words"] = {"pass": 2500 <= n <= 5000, "detail": n}

    style_hits = []
    for doc in ["README.md", "TECHNICAL.md", "results/FINDINGS.md"]:
        p = ROOT / doc
        if not p.exists():
            continue
        prose = cut_references(strip_markup(p.read_text(), keep_math=False)).lower()
        for w in BANNED:
            if re.search(rf"\b{re.escape(w)}\b", prose):
                style_hits.append(f"{doc}: banned '{w}'")
        if "—" in p.read_text():
            style_hits.append(f"{doc}: em-dash")
        if re.search(r"(?<![-!<])--(?![->])", strip_markup(p.read_text())):
            style_hits.append(f"{doc}: double hyphen")
    ok["prose_style"] = {"pass": not style_hits, "detail": style_hits}

    tracked = subprocess.run(["git", "ls-files"], capture_output=True, text=True, cwd=ROOT).stdout.split()
    files = tracked or [str(p.relative_to(ROOT)) for p in ROOT.rglob("*") if p.is_file() and ".venv" not in p.parts
                        and ".git" not in p.parts and "papers" not in p.parts and "__pycache__" not in p.parts]
    ai_hits, secret_hits, big = [], [], []
    for f in files:
        p = ROOT / f
        if p.stat().st_size > 10 * 1024 * 1024:
            big.append(f)
        if p.suffix in {".md", ".py", ".yml", ".txt", ".json", ".toml", ".cfg"} or p.name in {"Makefile", ".gitignore"}:
            t = p.read_text(errors="ignore")
            if f != "src/05_audit.py" and AUTHORSHIP.search(t):
                ai_hits.append(f)
            if SECRET.search(t):
                secret_hits.append(f)
    log = subprocess.run(["git", "log", "--format=%an%n%ae%n%B"], capture_output=True, text=True, cwd=ROOT).stdout
    if AUTHORSHIP.search(log) or "Co-Authored-By" in log:
        ai_hits.append("git log")
    ok["no_authorship_references"] = {"pass": not ai_hits, "detail": ai_hits}
    ok["no_secrets"] = {"pass": not secret_hits, "detail": secret_hits}
    ok["no_file_over_10MB"] = {"pass": not big, "detail": big}

    fig_issues = []
    if (ROOT / "README.md").exists():
        for ref in re.findall(r"!\[[^\]]*\]\(([^)]+\.png)\)", (ROOT / "README.md").read_text()):
            p = ROOT / ref
            if not p.exists():
                fig_issues.append(f"missing {ref}")
                continue
            dpi = Image.open(p).info.get("dpi", (0, 0))[0]
            if round(dpi) < 299:
                fig_issues.append(f"{ref} at {dpi} dpi")
    ok["figures_exist_300dpi"] = {"pass": not fig_issues, "detail": fig_issues}

    bib_issues = []
    if (ROOT / "TECHNICAL.md").exists():
        t = (ROOT / "TECHNICAL.md").read_text()
        m = re.search(r"^#+\s*(?:\d+\.\s*)?(References|Bibliography)\s*$", t, flags=re.M | re.I)
        entries = [ln for ln in t[m.end():].splitlines() if ln.strip().startswith("- ")] if m else []
        if not entries:
            bib_issues.append("no bibliography found")
        bib_issues += [e[:60] for e in entries if "doi.org" not in e and "http" not in e]
    ok["bibliography_links"] = {"pass": not bib_issues, "detail": bib_issues}

    report["all_pass"] = all(v["pass"] for v in ok.values())
    report["gates_failed"] = [k for k, v in ok.items() if not v["pass"]]
    (ROOT / "run_report.json").write_text(json.dumps(report, indent=2, default=str) + "\n")
    for k, v in ok.items():
        print(f"{'PASS' if v['pass'] else 'FAIL'}  {k}  {'' if v['pass'] else v['detail']}")
    return 0 if report["all_pass"] else 1


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--full", action="store_true")
    sys.exit(main(ap.parse_args().full))
